Temperatura = float(input("Ingrese la temperatura en Cº: "))
F = (Temperatura * 9/5) + 32
K = (Temperatura + 273.15)
print(Temperatura,"Cº son ", F ,"ºF")
print(Temperatura,"Cº son ", K,"K")



